const PREFIX_ESC = "\x1b[";
const SUFFIX_HIDE = "l";
const SUFFIX_SHOW = "h";

const SUFFIX_CURSOR = " q";
pub const CURSOR_BLOCK = PREFIX_ESC ++ "2" ++ SUFFIX_CURSOR;
pub const CURSOR_BAR = PREFIX_ESC ++ "6" ++ SUFFIX_CURSOR;

const PREFIX_CURSOR_VISIBLE = "?25";
pub const CURSOR_INVISIBLE = PREFIX_ESC ++ PREFIX_CURSOR_VISIBLE ++ SUFFIX_HIDE;
pub const CURSOR_VISIBLE = PREFIX_ESC ++ PREFIX_CURSOR_VISIBLE ++ SUFFIX_SHOW;

const CURSOR_SET = "H";
pub const CURSOR_HOME = PREFIX_ESC ++ CURSOR_SET;
pub const CURSOR_SET_TEMPLATE = PREFIX_ESC ++ "{d};{d}" ++ CURSOR_SET;

const SUFFIX_CURSOR_RIGHT = "C";
const SUFFIX_CURSOR_DOWN = "B";
pub fn cursorMove(comptime right: []const u8, comptime down: []const u8) []const u8 {
    return PREFIX_ESC ++ right ++ SUFFIX_CURSOR_RIGHT ++ PREFIX_ESC ++ down ++ SUFFIX_CURSOR_DOWN;
}

const SUFFIX_CURSOR_REQUEST = "6n";
pub const CURSOR_REQUEST = PREFIX_ESC ++ SUFFIX_CURSOR_REQUEST;

const SUFFIX_ERASE_LINE = "K";
const SUFFIX_ERASE_SCREEN = "J";
const PREFIX_ERASE_ENTIRE = "2";
pub const ERASE_LINE_END = PREFIX_ESC ++ SUFFIX_ERASE_LINE;
pub const ERASE_SCREEN = PREFIX_ESC ++ PREFIX_ERASE_ENTIRE ++ SUFFIX_ERASE_SCREEN;

const PREFIX_ALT_BUFFER = "?1049";
pub const ALT_BUFFER_ENABLE = PREFIX_ESC ++ PREFIX_ALT_BUFFER ++ SUFFIX_SHOW;
pub const ALT_BUFFER_DISABLE = PREFIX_ESC ++ PREFIX_ALT_BUFFER ++ SUFFIX_HIDE;

const SUFFIX_MODE = "m";
pub const RESET_MODE = PREFIX_ESC ++ "0" ++ SUFFIX_MODE;
